def now():
    return dt.datetime.now(dt.timezone.utc).isoformat(timespec="seconds")


def uid(prefix):
    return prefix + "-" + uuid.uuid4().hex[:12]


def digest(data):
    return hashlib.sha256(data).hexdigest()


def check_text(value, label="内容", limit=20000):
    if not isinstance(value, str) or not value.strip():
        raise KBError(label + "不能为空")
    if len(value) > limit:
        raise KBError(label + "超过长度限制")
    if "\x00" in value or any(p.search(value) for p in SECRET_PATTERNS):
        raise KBError(label + "疑似含密钥、口令或无效字符；请脱敏后再提供")
    return value.strip()


def no_symlinks(path):
    p = Path(os.path.abspath(os.path.expanduser(str(path))))
    for part in [p] + list(p.parents):
        if part.is_symlink():
            raise KBError("不跟随符号链接：" + str(part))
        if os.name == "nt" and part.exists():
            attrs = getattr(part.lstat(), "st_file_attributes", 0)
            if attrs & getattr(stat, "FILE_ATTRIBUTE_REPARSE_POINT", 0x400):
                raise KBError("不跟随 Windows 重解析点或目录联接：" + str(part))
    return p


def root_path(value):
    root = no_symlinks(value)
    if root == Path(root.anchor) or root == Path.home():
        raise KBError("请选择专门的工作区文件夹，不要使用磁盘根目录或用户主目录")
    if root.exists() and not root.is_dir():
        raise KBError("工作区不是文件夹")
    return root


def inside(root, relative):
    rel = Path(relative)
    if rel.is_absolute() or ".." in rel.parts or "\\" in str(relative) or ":" in str(relative):
        raise KBError("拒绝越界路径")
    p = no_symlinks(root / rel)
    try:
        p.relative_to(root)
    except ValueError:
        raise KBError("拒绝越界路径")
    if p.exists() and p.is_file() and p.stat().st_nlink > 1:
        raise KBError("拒绝写入或读取受管理的硬链接")
    return p


def _atomic(path, data):
    path = no_symlinks(path)
    if path.exists() and (not path.is_file() or path.stat().st_nlink > 1):
        raise KBError("目标不是安全的普通文件：" + str(path))
    path.parent.mkdir(parents=True, exist_ok=True)
    if isinstance(data, str):
        data = data.encode("utf-8")
    fd, temp = tempfile.mkstemp(prefix=".chao-write-", dir=str(path.parent))
    try:
        with os.fdopen(fd, "wb") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.replace(temp, path)
    finally:
        if os.path.exists(temp):
            os.unlink(temp)


# One command stages every file before applying it. The journal is retained only
# after interruption or failed rollback; it is never an automatic repair signal.
_TRANSACTION = None


def atomic(path, data):
    if _TRANSACTION is None:
        return _atomic(path, data)
    path = no_symlinks(path)
    if path.exists() and (not path.is_file() or path.stat().st_nlink > 1):
        raise KBError("目标不是安全的普通文件：" + str(path))
    path.relative_to(_TRANSACTION["root"])
    _TRANSACTION["writes"][path] = data.encode("utf-8") if isinstance(data, str) else data


@contextlib.contextmanager
def transaction(root):
    global _TRANSACTION
    if _TRANSACTION is not None:
        raise KBError("不支持嵌套写入")
    pending = inside(root, STORE + "/pending-write.json")
    if pending.exists():
        raise KBError("上次写入未完成；先运行 recover 查看恢复范围，不继续覆盖")
    _TRANSACTION = {"root": root, "writes": {}}
    try:
        yield
        writes = _TRANSACTION["writes"]
    finally:
        _TRANSACTION = None
    if not writes:
        return
    # Recheck all paths after staging, before touching any destination.
    old = {}
    for path in writes:
        inside(root, path.relative_to(root).as_posix())
        if path.exists() and path.stat().st_size > MAX_BYTES:
            raise KBError("目标过大，停止写入：" + path.relative_to(root).as_posix())
        old[path] = path.read_bytes() if path.exists() else None
    # A compact single-file undo journal avoids producing/deleting one backup
    # per mirror on every operation (and tripping host bulk-delete guards).
    writes = {path:data for path,data in writes.items() if old[path]!=data}
    if not writes: return
    records = [{"path":path.relative_to(root).as_posix(), "before":digest(old[path]) if old[path] is not None else None,
                "after":digest(data), "data":base64.b64encode(old[path]).decode("ascii") if old[path] is not None else None}
               for path,data in writes.items()]
    journal_data=json.dumps({"format":1,"files":records},ensure_ascii=False)
    if len(journal_data.encode())>2*MAX_BYTES: raise KBError("这次写入范围过大，请按项目拆分；本次未覆盖任何文件")
    _atomic(pending,journal_data)
    applied = []
    try:
        ordered = sorted(writes, key=lambda p: p == root / STORE / "state.json")
        for path in ordered:
            # Detect edits between preflight and commit; do not overwrite them.
            inside(root,path.relative_to(root).as_posix())
            current=path.read_bytes() if path.is_file() else None
            if current!=old[path]: raise KBError("文件在写入前被其他任务修改；本次停止："+path.relative_to(root).as_posix())
            applied.append(path)
            _atomic(path, writes[path])
    except BaseException:
        try:
            for path in reversed(applied):
                inside(root,path.relative_to(root).as_posix())
                current=path.read_bytes() if path.is_file() else None
                if current not in (old[path],writes[path]): raise KBError("回滚目标后来又被修改；保留恢复记录")
                if old[path] is None:
                    if path.exists(): path.unlink()
                else: _atomic(path, old[path])
        except BaseException:
            raise KBError("写入中断且回滚未完成；保留恢复记录，请运行 recover，勿删除原资料")
        pending.unlink()
        raise
    pending.unlink()


def recover(root, apply=False, quote=None):
    pending = inside(root, STORE + "/pending-write.json")
    if not pending.is_file():
        return {"status": "nothing_to_recover", "files": []}
    if pending.stat().st_size>2*MAX_BYTES: raise KBError("恢复记录过大；请保留现场")
    obj = json.loads(pending.read_text(encoding="utf-8"))
    journal = inside(root,obj["journal"]) if "journal" in obj else None
    if journal and not re.fullmatch(r"\.chao/transactions/t-[a-f0-9]{12}",journal.relative_to(root).as_posix()):
        raise KBError("恢复目录无效；请保留现场")
    backups = {}
    for row in obj["files"]:
        path = inside(root, row["path"])
        # A journal cannot target arbitrary workspace files.
        if not (row["path"] in view_documents(empty_state()) or row["path"] in ("AGENTS.md", ".gitignore")
                or row["path"] == STORE + "/state.json" or row["path"].startswith(STORE + "/backups/")
                or re.fullmatch(r"04-项目/项目-[^/]+-[a-f0-9]{12}\.md",row["path"])
                or re.fullmatch(r"02-资料库/(?:对标内容|用户反馈|行业资料|素材)/_资料/m-[a-f0-9]{12}/(?:original[^/]*|text.txt|extracted.txt)",row["path"])
                or re.fullmatch(r"03-内容中心/(?:选题池|草稿|待确认|已完成|已发布与复盘)/[of]-[a-f0-9]{12}(?:\.md|\.json|\.sources\.json|\.依据\.md)",row["path"])):
            raise KBError("恢复目标超出知识库管理范围")
        current = digest(path.read_bytes()) if path.is_file() else None
        if current not in (row["before"], row["after"]):
            raise KBError("恢复目标后来又被修改；停止自动恢复：" + row["path"])
        if row.get("backup"):
            if not journal: raise KBError("恢复目录缺失")
            backup = inside(root,row["backup"]); backup.relative_to(journal)
            if not backup.is_file() or backup.stat().st_size>MAX_BYTES: raise KBError("恢复备份缺失或过大")
            data=backup.read_bytes()
        elif row.get("data") is not None:
            data=base64.b64decode(row["data"],validate=True)
        else: data=None
        if (digest(data) if data is not None else None)!=row["before"]: raise KBError("恢复备份损坏；停止恢复")
        backups[row["path"]]=data
    result = {"status": "plan", "files": [r["path"] for r in obj["files"]], "action": "恢复到该次写入前的版本；移除该次新建的受管理文件"}
    if apply:
        check_text(quote, "恢复确认", 1000)
        for row in reversed(obj["files"]):
            path = inside(root, row["path"])
            if backups[row["path"]] is not None:
                _atomic(path,backups[row["path"]])
            elif path.exists():
                path.unlink()
        pending.unlink()
        if journal: shutil.rmtree(journal)
        result["status"] = "recovered"
    return result


