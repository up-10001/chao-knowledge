    if (root / STORE / "state.json").exists():
        with lock(root), transaction(root):
            state = load(root)
            drift = view_drift(root, state, allow_legacy=state["schema"] == 1)
            if drift:
                raise KBError("可读文件有手工改动，已保留；先运行 sync 查看范围：" + "、".join(drift))
            migration = state["schema"] == 1
