def execute(args):
    root = root_path(args.root)
    if hasattr(args, "limit") and not 1 <= args.limit <= 10:
        raise KBError("limit 必须为 1 到 10")
    if args.cmd == "init":
        return initialize(root)
    with lock(root):
        state = load(root)
        write = True
        if args.cmd == "profile":
            value = check_text(args.value, "档案字段", 2000)
            quote = check_text(args.quote, "用户陈述", 2000)
            state["profile"][args.field] = {"value": value, "source": "user_statement", "quote": quote, "updated_at": now()}
            audit(state, "profile_updated", args.field)
            result = {"field": args.field, "profile": state["profile"][args.field]}
        elif args.cmd == "ingest": result = ingest(root, state, args)
        elif args.cmd == "extract": result = extract(root, state, args)
        elif args.cmd == "remember": result = propose(state, args)
        elif args.cmd == "confirm": result = confirm(state, args)
        elif args.cmd in ("revoke", "forget"):
            check_text(args.quote, "撤销/删除确认", 1000)
            row = get_record(state, "rules", args.id)
            if args.cmd == "forget":
                del state["rules"][args.id]
            else:
                row["status"] = "revoked"
            audit(state, "rule_" + args.cmd, args.id)
            result = {"id": args.id, "status": "forgotten" if args.cmd == "forget" else "revoked",
                      "warning": "撤销不再调用；forget 从当前规则库移除内容，不会擦除宿主聊天记录、旧作品、系统备份或磁盘历史"}
        elif args.cmd == "save": result = save_output(root, state, args)
        elif args.cmd == "approve": result = approve_output(root, state, args)
        elif args.cmd == "feedback": result = feedback(root, state, args)
        else:
            write = False
            if args.cmd == "search": result = search(root, state, args.query, args.limit)
            elif args.cmd == "context": result = context(root, state, args)
            elif args.cmd == "rules": result = {"rules": list(state["rules"].values())}
            elif args.cmd == "health": result = health(root, state)
            else: raise KBError("未知命令")
        if write:
            save_state(root, state)
        return result


def main(argv=None):
    for stream in (sys.stdout, sys.stderr):
        if hasattr(stream, "reconfigure"):
            stream.reconfigure(encoding="utf-8")
    args = build_parser().parse_args(argv)
    try:
        result = execute(args)
        print(json.dumps({"ok": True, "result": result}, ensure_ascii=False, indent=2, allow_nan=False))
        return 0
    except (KBError, OSError, UnicodeError, ValueError, KeyError, TypeError) as exc:
        print(json.dumps({"ok": False, "error": str(exc)}, ensure_ascii=False), file=sys.stderr)
        return 2


if __name__ == "__main__":
    sys.exit(main())
