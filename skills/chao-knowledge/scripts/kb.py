def strict_pairs(pairs):
    obj={}
    for key,value in pairs:
        if key in obj: raise ValueError("重复状态字段："+key)
        obj[key]=value
    return obj


def invalid_constant(value):
    raise ValueError("状态中含无效数字："+value)

def load(root):
    p = inside(root, STORE + "/state.json")
    if not p.is_file():
        raise KBError("尚未初始化；请先运行 init")
    if p.stat().st_size > MAX_BYTES:
        raise KBError("状态文件过大；请按项目拆分")
    try:
        obj = json.loads(p.read_text(encoding="utf-8"),object_pairs_hook=strict_pairs,parse_constant=invalid_constant)
    except (ValueError, UnicodeError):
        raise KBError("状态文件损坏；不要覆盖，请从自己的备份恢复")
    if not isinstance(obj, dict) or obj.get("schema") not in (1, SCHEMA) or obj.get("app") != "chao-knowledge":
        raise KBError("状态文件格式不兼容；停止写入")
    if p.stat().st_size > MAX_BYTES:
        raise KBError("状态文件过大；停止读取，请按项目拆分")
    for key in ("profile", "materials", "rules", "outputs", "feedback"):
        if not isinstance(obj.get(key), dict):
            raise KBError("状态文件结构无效：" + key)
    required = {
        "materials": ("id", "title", "dedupe_key", "sha256", "original", "text_path", "text_sha256", "status", "sources", "tags", "created_at", "provenance"),
        "rules": ("id", "key", "text", "scope", "expires_on", "status", "created_at", "confirmation"),
        "outputs": ("id", "title", "path", "sha256", "status", "sources", "parent", "created_at", "review"),
        "feedback": ("id", "output_id", "metrics", "rates", "created_at"),
    }
    try:
        for field, row in obj["profile"].items():
            if not isinstance(row, dict) or not isinstance(row.get("value"), str) or not isinstance(row.get("quote"), str) or row.get("source") != "user_statement":
                raise ValueError("profile:" + field)
        for group, fields in required.items():
            for rid, row in obj[group].items():
                if not isinstance(row, dict) or any(k not in row for k in fields) or row["id"] != rid:
                    raise ValueError(group + ":" + rid)
                for field in ("title","path","original","created_at","key","text","sha256","provenance"):
                    if field in row and not isinstance(row[field],str): raise ValueError(group+":"+field)
                if not re.fullmatch(r"[mrof]-[a-f0-9]{12}",rid): raise ValueError("record id")
                if group == "rules":
                    if row["status"] not in ("proposed", "active", "revoked", "superseded") or not isinstance(row["scope"], dict):
                        raise ValueError("rules:" + rid)
                    parse_scope([k + "=" + v for k, v in row["scope"].items()])
                    if row["expires_on"]: dt.date.fromisoformat(row["expires_on"])
                    if row["status"] == "active" and (not isinstance(row["confirmation"], dict) or not isinstance(row["confirmation"].get("quote"),str) or not row["confirmation"]["quote"].strip()): raise ValueError("confirmation")
                elif group == "materials":
                    if row["provenance"] not in {"external","user_statement","user_original","demo"}: raise ValueError("provenance")
                    if row["status"] not in ("link_only", "needs_extraction", "text_available", "extracted_unverified"):
                        raise ValueError("material status")
                    if not isinstance(row["sources"], list) or not isinstance(row["tags"], list): raise ValueError("sources/tags")
                    if any(not isinstance(t,str) for t in row["tags"]): raise ValueError("tags")
                    if any(not isinstance(src,dict) or not isinstance(src.get("kind"),str) or not isinstance(src.get("location"),str) for src in row["sources"]): raise ValueError("source metadata")
                    if row["text_path"] is not None and not isinstance(row["text_path"],str): raise ValueError("text_path")
                    if row.get("valid_until"): dt.date.fromisoformat(row["valid_until"])
                elif group == "outputs":
                    if not isinstance(row["sources"], list) or row["status"] not in ("draft","approved","published"): raise ValueError("output sources/status")
                    for src in row["sources"]:
                        if not isinstance(src,dict) or any(k not in src for k in ("id","path","text_sha256","title","status","provenance")): raise ValueError("source card")
                elif group == "feedback":
                    if not isinstance(row["metrics"],dict) or not isinstance(row["rates"],dict) or "window_hours" not in row["metrics"]: raise ValueError("feedback metrics")
        for row in obj.get("experience",{}).values():
            if not isinstance(row,dict) or any(k not in row for k in ("id","title","text","status","scope","feedback_ids","created_at")):
                raise ValueError("experience")
            if row["status"] not in ("observation","hypothesis","experiment","validated","revoked") or not isinstance(row["scope"],dict) or not isinstance(row["feedback_ids"],list): raise ValueError("experience status/scope")
        if not isinstance(obj.get("events", []), list) or not isinstance(obj.get("views", {}), dict) or not isinstance(obj.get("experience", {}), dict):
            raise ValueError("events/views/experience")
    except (ValueError, TypeError, KeyError, KBError) as exc:
        raise KBError("状态记录损坏；停止写入，请保留文件并从可信备份恢复：" + str(exc))
    return obj


@contextlib.contextmanager
def lock(root, wait_seconds=0):
    store = inside(root, STORE)
    if not store.is_dir():
        raise KBError("尚未初始化")
    p = inside(root, STORE + "/LOCK")
    deadline=time.monotonic()+wait_seconds
    while True:
        try:
            p.mkdir()
            break
        except FileExistsError:
            if time.monotonic()>=deadline:
                raise KBError("工作区正在处理另一个任务，或上次异常退出留下 LOCK；稍后重试，勿强制并发写入")
            time.sleep(0.05)
    try:
        yield
    finally:
        p.rmdir()


def save_state(root, state):
    state["updated_at"] = now()
    data=json.dumps(state,ensure_ascii=False,indent=2,allow_nan=False)+"\n"
    if len(data.encode())>MAX_BYTES: raise KBError("状态超过 32 MiB，请按项目拆分知识库；本次未写入")
    atomic(inside(root,STORE+"/state.json"),data)


def audit(state, action, record_id):
    # Do not duplicate personal text into an append-only audit log.
    state.setdefault("events", []).append({"at": now(), "action": action, "id": record_id})
    state["events"] = state["events"][-500:]


def profile_value(state, field):
    row = state.get("profile", {}).get(field)
    return row.get("value", "") if isinstance(row, dict) else ""


def ensure_layout(root):
    paths = [inside(root, rel) for rel in DIRS + (STORE,)]
    for p in paths:
        if p.exists() and not p.is_dir():
            raise KBError("知识库结构冲突，期望文件夹：" + p.relative_to(root).as_posix())
    for p in paths: p.mkdir(parents=True, exist_ok=True)


def ensure_private_ignores(root, existing=None):
    p = inside(root, ".gitignore")
    if existing is None:
        if p.exists():
            if not p.is_file() or p.stat().st_size > MAX_TEXT:
                raise KBError("已有 .gitignore 不适合自动追加")
            existing = p.read_text(encoding="utf-8")
        else:
            existing = ""
    lines = ["/.chao/", "/00-收件箱/", "/01-我的档案/", "/02-资料库/", "/03-内容中心/", "/04-项目/", "/05-经验与规则/", "/开始这里.md", "/本周重点.md", "/知识库地图.md"]
    missing = [line for line in lines if line not in existing.splitlines()]
    if missing:
        text=existing+("\n" if existing and not existing.endswith("\n") else "")
        text+="\n# Chao Knowledge: private runtime data; do not publish\n"+"\n".join(missing)+"\n"
        atomic(p,text)


