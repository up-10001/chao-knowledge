def initialize(root):
    root.mkdir(parents=True, exist_ok=True)
    p = inside(root, ".chao-init-lock")
    try: p.mkdir()
    except FileExistsError: raise KBError("另一个任务正在初始化；请稍后重试，不强制解锁")
    try: return _initialize(root)
    finally: p.rmdir()


def state_fingerprint(state):
    return digest(json.dumps({k:v for k,v in state.items() if k not in {"migration","updated_at","views"}},ensure_ascii=False,sort_keys=True).encode())


def rollback_migration(root,state,apply=False,quote=None):
    migration=state.get("migration",{})
    if not migration.get("checkpoint") or migration["checkpoint"]!=state_fingerprint(state):
        raise KBError("升级后已有新的数据修改，不能用旧状态覆盖；保留当前库，使用完整备份另建工作区恢复")
    if view_drift(root,state): raise KBError("升级后可读文件又有手工改动；先保留并核对，不能自动回滚")
    for rel,expected in migration.get("config_hashes",{}).items():
        if rel not in {"AGENTS.md",".gitignore"}: raise KBError("回滚配置无效")
        p=inside(root,rel)
        if not p.is_file() or digest(p.read_bytes())!=expected: raise KBError("升级后配置被修改，不能覆盖："+rel)
    backup=inside(root,migration["backup"])
    if not re.fullmatch(r"\.chao/backups/pre-v0\.3-[a-f0-9]{12}",backup.relative_to(root).as_posix()): raise KBError("升级备份路径无效")
    state_backup=inside(root,migration["backup"]+"/state.json")
    old=json.loads(state_backup.read_text(encoding="utf-8"))
    if old.get("app")!="chao-knowledge" or old.get("schema")!=1: raise KBError("升级备份格式无效")
    targets={STORE+"/state.json":state_backup.read_bytes()}
    for rel in list(view_documents(state))+["AGENTS.md",".gitignore"]:
        p=inside(root,migration["backup"]+"/"+rel)
        if p.is_file(): targets[rel]=p.read_bytes()
    result={"status":"plan","files":list(targets),"action":"恢复升级前的状态与入口；保留原件、作品及新增文件，不删除个人数据"}
    if apply:
        check_text(quote,"回滚确认",1000)
        for rel,data in targets.items(): atomic(inside(root,rel),data)
        result["status"]="restored"
    return result

def parse_scope(values):
    out = {}
    for item in values or []:
        if "=" not in item:
            raise KBError("scope 格式为 task=口播，可重复传入")
        key, value = item.split("=", 1)
        if key not in SCOPE_FIELDS or key in out:
            raise KBError("scope 字段无效或重复")
        out[key] = check_text(value, "适用场景", 100)
    return out


def relative_sibling(relative, filename):
    p = PurePosixPath(str(relative))
    if p.is_absolute() or ".." in p.parts or "\\" in str(relative) or ":" in str(relative):
        raise KBError("内部相对路径无效")
    name = check_text(filename, "文件名", 255)
    if "/" in name or "\\" in name or name in (".", ".."):
        raise KBError("内部文件名无效")
    return str(p.parent / name)


def input_file(root, value, allow_external=False):
    p = Path(value).expanduser()
    p = no_symlinks(p if p.is_absolute() else root / p)
    try:
        p.relative_to(root)
    except ValueError:
        if not allow_external:
            raise KBError("资料在工作区之外；只有用户明确提供该文件时才能加 --allow-external")
    if any(part.lower() in {".ssh", ".aws", ".azure", ".gnupg", ".git"} or part.lower().startswith(".env") for part in p.parts):
        raise KBError("不读取凭证目录或环境变量文件")
    if not p.is_file() or p.stat().st_nlink > 1 or p.stat().st_size > MAX_BYTES:
        raise KBError("文件不存在、不是普通文件或大于 32 MiB；请提供较小文件/逐字稿")
    with p.open("rb") as f:
        info=os.fstat(f.fileno())
        if not stat.S_ISREG(info.st_mode) or info.st_nlink>1 or (info.st_ino,info.st_dev)!=(p.stat().st_ino,p.stat().st_dev):
            raise KBError("资料文件发生变化或为硬链接；未读取")
        data = f.read(MAX_BYTES + 1)
    if len(data) > MAX_BYTES:
        raise KBError("文件过大")
    return p, data


def decode(data):
    if len(data) > MAX_TEXT:
        raise KBError("文本超过 2 MiB；请拆分资料后再导入")
    try:
        text = data.decode("utf-8-sig")
    except UnicodeError:
        raise KBError("当前只自动读取 UTF-8 文本；请转码或交给宿主读取后提供 UTF-8 副本")
    check_text(text, "资料", MAX_TEXT)
    return text


def valid_url(value):
    from urllib.parse import urlsplit, parse_qs
    value = check_text(value, "链接", 2000)
    obj = urlsplit(value)
    if obj.scheme not in ("https", "http") or not obj.hostname or obj.username or obj.password:
        raise KBError("只接受不含账号密码的 HTTP(S) 链接")
    if any(re.search(r"(?i)token|key|secret|password|signature|auth|credential", key) for key in parse_qs(obj.query+"&"+obj.fragment, keep_blank_values=True)):
        raise KBError("链接疑似含私密令牌；请提供可公开分享的来源链接")
    if obj.hostname.lower() in {"localhost"} or any(c in value for c in ("\n", "\r")):
        raise KBError("请提供可公开分享的来源链接")
    return value


